-- Store Management System: schema, stored procedures, application user and demo data.
-- Loaded by docker-compose on the first start and by the integration tests.
-- Dates in the demo data are relative to the moment the script runs.

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS audit_log, stavka_nabvke, nabavka, stavka, racun, proizvod_has_popust, popust,
                     proizvod, dobavljac, proizvodjac, kategorija, korisnik, tema, jezik;
DROP PROCEDURE IF EXISTS InsertRacunWithStavka;
DROP PROCEDURE IF EXISTS InsertNabavka;

SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE jezik (
  idJezik INT NOT NULL AUTO_INCREMENT,
  Naziv VARCHAR(45) NOT NULL,
  PRIMARY KEY (idJezik)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE tema (
  idTema INT NOT NULL AUTO_INCREMENT,
  boja VARCHAR(45) NOT NULL,
  font VARCHAR(45) NOT NULL,
  `veličina` VARCHAR(45) NOT NULL,
  fontStil VARCHAR(45) DEFAULT NULL,
  strikeout TINYINT DEFAULT 0,
  underline TINYINT DEFAULT 0,
  PRIMARY KEY (idTema)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE korisnik (
  idKorisnik INT NOT NULL AUTO_INCREMENT,
  Ime VARCHAR(45) NOT NULL,
  Prezime VARCHAR(45) NOT NULL,
  KorisnickoIme VARCHAR(45) NOT NULL,
  Lozinka VARCHAR(255) NOT NULL,
  idJezik INT NOT NULL,
  BrojTelefona VARCHAR(45) NOT NULL,
  Email VARCHAR(100) NOT NULL,
  isAdmin TINYINT NOT NULL,
  idTema INT NOT NULL,
  Slika MEDIUMBLOB NULL,
  PRIMARY KEY (idKorisnik),
  UNIQUE KEY KorisnickoIme_UNIQUE (KorisnickoIme),
  CONSTRAINT fk_Korisnik_Jezik FOREIGN KEY (idJezik) REFERENCES jezik (idJezik),
  CONSTRAINT fk_Korisnik_Tema FOREIGN KEY (idTema) REFERENCES tema (idTema)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE kategorija (
  idKategorija INT NOT NULL AUTO_INCREMENT,
  Naziv VARCHAR(45) NOT NULL,
  PRIMARY KEY (idKategorija),
  UNIQUE KEY Naziv_UNIQUE (Naziv)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE proizvodjac (
  idProizvodjac INT NOT NULL AUTO_INCREMENT,
  Ime VARCHAR(45) NOT NULL,
  Email VARCHAR(100) NOT NULL,
  PRIMARY KEY (idProizvodjac),
  UNIQUE KEY Ime_UNIQUE (Ime)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE dobavljac (
  idDobavljac INT NOT NULL AUTO_INCREMENT,
  Ime VARCHAR(45) NOT NULL,
  Email VARCHAR(100) NOT NULL,
  PRIMARY KEY (idDobavljac),
  UNIQUE KEY Ime_UNIQUE (Ime)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE proizvod (
  idProizvod INT NOT NULL AUTO_INCREMENT,
  Naziv VARCHAR(45) NOT NULL,
  Cijena DECIMAL(10,2) NOT NULL,
  Zalihe DECIMAL(10,2) NOT NULL,
  DatumIsteka DATE NOT NULL,
  BarKod VARCHAR(45) NOT NULL,
  idProizvodjac INT NOT NULL,
  Opis VARCHAR(255) DEFAULT NULL,
  idKategorija INT NOT NULL,
  Slika MEDIUMBLOB NULL,
  PRIMARY KEY (idProizvod),
  UNIQUE KEY BarKod_UNIQUE (BarKod),
  KEY ix_proizvod_naziv (Naziv),
  CONSTRAINT chk_proizvod_cijena CHECK (Cijena >= 0),
  CONSTRAINT chk_proizvod_zalihe CHECK (Zalihe >= 0),
  CONSTRAINT fk_Proizvod_Kategorija FOREIGN KEY (idKategorija) REFERENCES kategorija (idKategorija),
  CONSTRAINT fk_Proizvod_Proizvodjac FOREIGN KEY (idProizvodjac) REFERENCES proizvodjac (idProizvodjac)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE racun (
  idRacun INT NOT NULL AUTO_INCREMENT,
  DatumKupovine DATETIME NOT NULL,
  idKorisnik INT NULL,
  PRIMARY KEY (idRacun),
  KEY ix_racun_datum (DatumKupovine),
  CONSTRAINT fk_Racun_Korisnik FOREIGN KEY (idKorisnik) REFERENCES korisnik (idKorisnik) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE stavka (
  idRacun INT NOT NULL,
  idProizvod INT NOT NULL,
  Kolicina DECIMAL(10,2) NOT NULL,
  Cijena DECIMAL(10,2) NOT NULL,
  PRIMARY KEY (idRacun, idProizvod),
  CONSTRAINT chk_stavka_kolicina CHECK (Kolicina > 0),
  CONSTRAINT fk_Stavka_Proizvod FOREIGN KEY (idProizvod) REFERENCES proizvod (idProizvod),
  CONSTRAINT fk_Stavka_Racun FOREIGN KEY (idRacun) REFERENCES racun (idRacun) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE nabavka (
  idNabavka INT NOT NULL AUTO_INCREMENT,
  `idDobavljač` INT NOT NULL,
  DatumKupovine DATETIME NOT NULL,
  idKorisnik INT NULL,
  PRIMARY KEY (idNabavka, `idDobavljač`),
  KEY ix_nabavka_datum (DatumKupovine),
  CONSTRAINT fk_Nabavka_Dobavljac FOREIGN KEY (`idDobavljač`) REFERENCES dobavljac (idDobavljac),
  CONSTRAINT fk_Nabavka_Korisnik FOREIGN KEY (idKorisnik) REFERENCES korisnik (idKorisnik) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE stavka_nabvke (
  idNabavka INT NOT NULL,
  `idDobavljač` INT NOT NULL,
  idProizvod INT NOT NULL,
  Kolicina DECIMAL(10,2) NOT NULL,
  Cijena DECIMAL(10,2) NOT NULL,
  PRIMARY KEY (idNabavka, `idDobavljač`, idProizvod),
  CONSTRAINT chk_stavka_nabavke_kolicina CHECK (Kolicina > 0),
  CONSTRAINT fk_StavkaNabavke_Nabavka FOREIGN KEY (idNabavka, `idDobavljač`) REFERENCES nabavka (idNabavka, `idDobavljač`) ON DELETE CASCADE,
  CONSTRAINT fk_StavkaNabavke_Proizvod FOREIGN KEY (idProizvod) REFERENCES proizvod (idProizvod)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE audit_log (
  idLog INT NOT NULL AUTO_INCREMENT,
  Vrijeme DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  idKorisnik INT NULL,
  Akcija VARCHAR(40) NOT NULL,
  Opis VARCHAR(255) NOT NULL,
  PRIMARY KEY (idLog),
  KEY ix_audit_vrijeme (Vrijeme),
  CONSTRAINT fk_Audit_Korisnik FOREIGN KEY (idKorisnik) REFERENCES korisnik (idKorisnik) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- A sale: one bill and its lines in a single transaction. The current price and stock are read with a row
-- lock, so two tills cannot sell the same last item; the stock never goes below zero.
DELIMITER ;;
CREATE PROCEDURE InsertRacunWithStavka(
    IN idKorisnik_param INT,
    IN DatumKupovine_param DATETIME,
    IN stavke_list JSON
)
BEGIN
    DECLARE i INT DEFAULT 0;
    DECLARE num_items INT;
    DECLARE idProizvod_val INT;
    DECLARE Kolicina_val DECIMAL(10,2);
    DECLARE Cijena_val DECIMAL(10,2);
    DECLARE Zalihe_val DECIMAL(10,2);
    DECLARE Istek_val DATE;
    DECLARE idRacun_val INT;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    SET num_items = IFNULL(JSON_LENGTH(stavke_list), 0);
    IF num_items = 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'EMPTY_DOCUMENT';
    END IF;

    START TRANSACTION;
    INSERT INTO racun (DatumKupovine, idKorisnik) VALUES (DatumKupovine_param, idKorisnik_param);
    SET idRacun_val = LAST_INSERT_ID();

    WHILE i < num_items DO
        SET idProizvod_val = JSON_UNQUOTE(JSON_EXTRACT(stavke_list, CONCAT('$[', i, '].IdProduct')));
        SET Kolicina_val = JSON_UNQUOTE(JSON_EXTRACT(stavke_list, CONCAT('$[', i, '].Amount')));
        SET Zalihe_val = NULL;

        SELECT Cijena, Zalihe, DatumIsteka INTO Cijena_val, Zalihe_val, Istek_val
        FROM proizvod WHERE idProizvod = idProizvod_val FOR UPDATE;

        IF Zalihe_val IS NULL THEN
            SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'PRODUCT_NOT_FOUND';
        END IF;
        IF Kolicina_val IS NULL OR Kolicina_val <= 0 THEN
            SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'INVALID_AMOUNT';
        END IF;
        IF Istek_val < CURDATE() THEN
            SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'PRODUCT_EXPIRED';
        END IF;
        IF Zalihe_val < Kolicina_val THEN
            SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'INSUFFICIENT_STOCK';
        END IF;

        INSERT INTO stavka (idRacun, idProizvod, Kolicina, Cijena)
        VALUES (idRacun_val, idProizvod_val, Kolicina_val, Cijena_val);
        UPDATE proizvod SET Zalihe = Zalihe - Kolicina_val WHERE idProizvod = idProizvod_val;

        SET i = i + 1;
    END WHILE;
    COMMIT;

    SELECT idRacun_val AS idRacun;
END ;;

-- A procurement from one supplier at the given purchase prices, in a single transaction.
CREATE PROCEDURE InsertNabavka(
    IN idDobavljac_param INT,
    IN idKorisnik_param INT,
    IN DatumKupovine_param DATETIME,
    IN stavke_list JSON
)
BEGIN
    DECLARE i INT DEFAULT 0;
    DECLARE num_items INT;
    DECLARE idProizvod_val INT;
    DECLARE Kolicina_val DECIMAL(10,2);
    DECLARE Cijena_val DECIMAL(10,2);
    DECLARE idNabavka_val INT;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    SET num_items = IFNULL(JSON_LENGTH(stavke_list), 0);
    IF num_items = 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'EMPTY_DOCUMENT';
    END IF;

    START TRANSACTION;
    INSERT INTO nabavka (`idDobavljač`, DatumKupovine, idKorisnik) VALUES (idDobavljac_param, DatumKupovine_param, idKorisnik_param);
    SET idNabavka_val = LAST_INSERT_ID();

    WHILE i < num_items DO
        SET idProizvod_val = JSON_UNQUOTE(JSON_EXTRACT(stavke_list, CONCAT('$[', i, '].IdProduct')));
        SET Kolicina_val = JSON_UNQUOTE(JSON_EXTRACT(stavke_list, CONCAT('$[', i, '].Amount')));
        SET Cijena_val = JSON_UNQUOTE(JSON_EXTRACT(stavke_list, CONCAT('$[', i, '].Price')));

        IF Kolicina_val IS NULL OR Kolicina_val <= 0 OR Cijena_val IS NULL OR Cijena_val < 0 THEN
            SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'INVALID_AMOUNT';
        END IF;

        INSERT INTO stavka_nabvke (idNabavka, `idDobavljač`, idProizvod, Kolicina, Cijena)
        VALUES (idNabavka_val, idDobavljac_param, idProizvod_val, Kolicina_val, Cijena_val);
        UPDATE proizvod SET Zalihe = Zalihe + Kolicina_val WHERE idProizvod = idProizvod_val;

        SET i = i + 1;
    END WHILE;
    COMMIT;

    SELECT idNabavka_val AS idNabavka;
END ;;
DELIMITER ;

